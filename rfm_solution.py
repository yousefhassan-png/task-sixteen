عنوان('الجزء 1 - السؤال 1: عميل اشترى مرة واحدة بمبلغ كبير مقابل عميل يشتري كل شهر بمبلغ صغير')
print('''العميل الأول اشترى مرة واحدة فقط منذ 3 سنوات: قيمة Recency عنده كبيرة جداً (غائب منذ مدة طويلة)
وFrequency تساوي 1، أما Monetary فكبيرة بسبب عملية واحدة فقط. هذا العميل غالباً فرصة لا تتكرر
وقد لا يعود أبداً. أما العميل الثاني فيشتري كل شهر فـ Recency صغيرة وFrequency عالية، ومع أن كل عملية
صغيرة إلا أن مجموع ما يدفعه خلال السنة قد يكون أكبر من العميل الأول، كما أنه عميل وفيّ نعرف
عادته ويمكننا توقع شرائه القادم. أهمية التفريق بينهما للمحلل: لو نظرنا إلى المبلغ وحده (Monetary)
سنعتقد أن العميل الأول أفضل، ونصرف عليه ميزانية تسويق بلا فائدة، وربما نهمل العميل المنتظم الذي
هو أساس استقرار الدخل. فلكل عميل معاملة مختلفة، وRFM تعطينا الصورة الكاملة بدل رقم واحد.''')

عنوان('الجزء 1 - السؤال 2: مثال على قرار تسويقي مختلف')
print('''العميل (R منخفض، F منخفض) أي نشط حديثاً لكنه لا يشتري كثيراً: هو عميل ما زال يتفاعل معنا، فالقرار
المناسب هو تشجيعه على تكرار الشراء، مثل إرسال رسالة بعد شرائه بأسبوعين تقترح عليه منتجات
مكملة لما اشتراه، أو عرض "اشترِ 3 مرات واحصل على خصم". لا داعي لخصم كبير لأنه لم يغادر بعد.
العميل (R مرتفع جداً، F عالٍ) أي كان يشتري كثيراً ثم اختفى: هذا عميل كان ثميناً ونحن نخسره، فالقرار
المناسب هو حملة استرجاع شخصية، مثل رسالة "اشتقنا لك" مع خصم خاص به، أو سؤاله عن سبب الغياب،
لأن استرجاع عميل قديم أرخص من البحث عن عميل جديد. الفرق: الأول نشجعه ليزيد، والثاني نسرع لننقذه.''')


# =====================================================================
# الجزء 2: حساب RFM وتطبيق K-Means
# =====================================================================
عنوان('الجزء 2 - تجهيز بيانات الطلبات من قاعدة البيانات')

# ملف الداتا بيس عبارة عن dump (أوامر SQL)، فننشئ قاعدة بيانات مؤقتة في الذاكرة ونشغّل الأوامر عليها
اسم_ملف_القاعدة = 'store_db_dump (1).txt'
اتصال = sqlite3.connect(':memory:')
with open(اسم_ملف_القاعدة, encoding='utf-8') as ملف:
    اتصال.executescript(ملف.read())

# جدول المبيعات ليس فيه عمود للمبلغ، فنحسب الإيراد = الكمية × سعر المنتج × (1 - الخصم)
# ونعيد تسمية الأعمدة لتطابق المطلوب في التاسك: customer_id, order_date, revenue
استعلام = '''
SELECT s.customer_id AS customer_id,
       s.sale_date   AS order_date,
       s.quantity * p.price * (1 - s.discount) AS revenue
FROM sales s
JOIN products p ON s.product_id = p.product_id
'''
بيانات_الطلبات = pd.read_sql(استعلام, اتصال)
اتصال.close()

# تحويل عمود التاريخ من نص إلى تاريخ حقيقي حتى نستطيع طرح التواريخ
بيانات_الطلبات['order_date'] = pd.to_datetime(بيانات_الطلبات['order_date'])

print('عدد الطلبات:', len(بيانات_الطلبات))
print('عدد العملاء:', بيانات_الطلبات['customer_id'].nunique())
print('القيم الفارغة في كل عمود:')
print(بيانات_الطلبات.isnull().sum())
print(بيانات_الطلبات.head())

# --- التمرين 1: حساب R و F و M لكل عميل ---
عنوان('الجزء 2 - التمرين 1: حساب Recency و Frequency و Monetary')

# آخر تاريخ في البيانات كاملة (نقطة المقارنة لحساب Recency)
آخر_تاريخ_في_البيانات = بيانات_الطلبات['order_date'].max()
print('آخر تاريخ في البيانات:', آخر_تاريخ_في_البيانات.date())

مجموعات_العملاء = بيانات_الطلبات.groupby('customer_id')

# Recency: الفرق بالأيام بين آخر تاريخ في البيانات وآخر شراء للعميل
آخر_شراء_لكل_عميل = مجموعات_العملاء['order_date'].max()
recency = (آخر_تاريخ_في_البيانات - آخر_شراء_لكل_عميل).dt.days

# Frequency: عدد عمليات الشراء
frequency = مجموعات_العملاء['order_date'].count()

# Monetary: إجمالي ما صرفه العميل
monetary = مجموعات_العملاء['revenue'].sum()

# نجمع الثلاثة في DataFrame واحد اسمه rfm (صف لكل عميل)
rfm = pd.DataFrame({'recency': recency, 'frequency': frequency, 'monetary': monetary})
print(rfm.head())
print()
print('ملخص إحصائي لجدول rfm:')
print(rfm.describe().round(2))

# تحقق سريع أن الحساب صحيح: مجموع الطلبات يجب أن يساوي مجموع Frequency
print()
print('تحقق: مجموع Frequency =', rfm['frequency'].sum(), '، وعدد الطلبات الأصلي =', len(بيانات_الطلبات))
print('تحقق: مجموع Monetary = {:.2f} ، ومجموع الإيراد الأصلي = {:.2f}'.format(
    rfm['monetary'].sum(), بيانات_الطلبات['revenue'].sum()))

# --- التمرين 2: StandardScaler ---
عنوان('الجزء 2 - التمرين 2: توحيد المقاييس بـ StandardScaler')
print('السبب: recency بالأيام وfrequency بالعدد وmonetary بالمئات والآلاف، وK-Means يعتمد على المسافات')
print('فلو لم نوحّد المقاييس لسيطر عمود monetary لأن أرقامه الأكبر.')
أداة_التوحيد = StandardScaler()
بيانات_موحدة = أداة_التوحيد.fit_transform(rfm[['recency', 'frequency', 'monetary']])
جدول_موحد = pd.DataFrame(بيانات_موحدة, columns=['recency', 'frequency', 'monetary'])
print('المتوسط بعد التوحيد (يجب أن يقارب 0):', جدول_موحد.mean().round(3).to_dict())
print('الانحراف المعياري بعد التوحيد (يجب أن يقارب 1):', جدول_موحد.std(ddof=0).round(3).to_dict())

# --- التمرين 3: Elbow Method من k=2 إلى k=7 ---
عنوان('الجزء 2 - التمرين 3: Elbow Method لاختيار عدد المجموعات')
قيم_k = list(range(2, 8))
قيم_inertia = []
قيم_silhouette = []
for k in قيم_k:
    نموذج_مؤقت = KMeans(n_clusters=k, random_state=42, n_init=10)
    نموذج_مؤقت.fit(بيانات_موحدة)
    قيم_inertia.append(نموذج_مؤقت.inertia_)
    # silhouette مقياس مساعد: كلما اقترب من 1 كان فصل المجموعات أوضح
    قيم_silhouette.append(silhouette_score(بيانات_موحدة, نموذج_مؤقت.labels_))

جدول_elbow = pd.DataFrame({'k': قيم_k, 'inertia': [round(ق, 1) for ق in قيم_inertia],
                           'silhouette': [round(ق, 3) for ق in قيم_silhouette]})
print(جدول_elbow.to_string(index=False))

plt.figure(figsize=(8, 5))
plt.plot(قيم_k, قيم_inertia, marker='o')
plt.title(عربي('طريقة Elbow لاختيار عدد المجموعات'))
plt.xlabel(عربي('عدد المجموعات (k)'))
plt.ylabel(عربي('مجموع المسافات داخل المجموعات (inertia)'))
plt.xticks(قيم_k)
احفظ_واعرض('رسمة_1_elbow.png')

# نختار k: النقطة التي يخف عندها انحدار المنحنى، ونعززها بأعلى قيمة silhouette
أفضل_k = قيم_k[قيم_silhouette.index(max(قيم_silhouette))]
print()
print(f'قراءة الرسمة: الانحدار حاد من k=2 إلى k=3 ثم يصبح أخف بعد k=3 (هذا هو الكوع)،')
print(f'وأعلى silhouette عند k={أفضل_k}. لذلك نختار k = {أفضل_k}.')

# --- التمرين 4: K-Means النهائي وإضافة عمود segment ---
عنوان('الجزء 2 - التمرين 4: تدريب K-Means النهائي')
النموذج_النهائي = KMeans(n_clusters=أفضل_k, random_state=42, n_init=10)
rfm['segment'] = النموذج_النهائي.fit_predict(بيانات_موحدة)
print(rfm.head(10))
print()
print('عدد العملاء في كل رقم مجموعة:')
print(rfm['segment'].value_counts().sort_index())


# =====================================================================
# الجزء 3: تفسير وتسمية المجموعات
# =====================================================================
عنوان('الجزء 3: متوسط R و F و M داخل كل مجموعة')
متوسطات_المجموعات = rfm.groupby('segment')[['recency', 'frequency', 'monetary']].mean()
print(متوسطات_المجموعات.round(1))

# نختار الأسماء من الأرقام نفسها (وليس عشوائياً):
#   - المجموعة ذات أعلى Recency (الأكثر غياباً)            -> عملاء بخطر فقدان
#   - المجموعة ذات أعلى Monetary بين الباقيتين (والأكثر شراءً) -> عملاء مميزون
#   - الباقية (أرقامها متوسطة)                              -> عملاء عاديون
رقم_الخطر = متوسطات_المجموعات['recency'].idxmax()
الباقي = متوسطات_المجموعات.drop(index=رقم_الخطر)
رقم_المميزين = الباقي['monetary'].idxmax()
رقم_العاديين = الباقي['monetary'].idxmin()

أسماء_المجموعات = {
    رقم_المميزين: 'عملاء مميزون',
    رقم_الخطر: 'عملاء بخطر فقدان',
    رقم_العاديين: 'عملاء عاديون',
}
rfm['اسم_المجموعة'] = rfm['segment'].map(أسماء_المجموعات)

# نلاحظ: لم تظهر مجموعة "عملاء جدد" لأن كل العملاء لديهم 4 عمليات شراء على الأقل (أقل F = 4)
print()
print('أقل قيمة Frequency في البيانات =', rfm['frequency'].min(), '، فلا يوجد عملاء "جدد" بشراء واحد أو اثنين.')

# أوصاف وتوصيات مبنية على الأرقام المحسوبة
وصف_المجموعات = {}
توصيات_المجموعات = {}
for رقم, اسم in أسماء_المجموعات.items():
    ر = متوسطات_المجموعات.loc[رقم, 'recency']
    ت = متوسطات_المجموعات.loc[رقم, 'frequency']
    م = متوسطات_المجموعات.loc[رقم, 'monetary']
    if اسم == 'عملاء مميزون':
        وصف_المجموعات[اسم] = (f'آخر شراء لهم قبل {ر:.0f} يوماً تقريباً، ويشترون {ت:.0f} مرة بالمتوسط وينفقون {م:,.0f} دولار. '
                              'هم أنشط عملائنا وأعلاهم قيمة، وعليهم يقوم جزء كبير من الدخل.')
        توصيات_المجموعات[اسم] = 'برنامج ولاء ونقاط مكافآت، وإتاحة المنتجات الجديدة لهم قبل غيرهم للحفاظ عليهم.'
    elif اسم == 'عملاء بخطر فقدان':
        وصف_المجموعات[اسم] = (f'غائبون منذ {ر:.0f} يوماً تقريباً (أطول غياب بين المجموعات)، وسبق أن اشتروا {ت:.0f} مرات '
                              f'بإجمالي {م:,.0f} دولار. عددهم قليل لكن غيابهم الطويل يدل على أنهم قد ينسوننا.')
        توصيات_المجموعات[اسم] = 'رسالة "اشتقنا لك" مع خصم شخصي محدود المدة لإرجاعهم، وسؤالهم عن سبب الغياب.'
    else:
        وصف_المجموعات[اسم] = (f'نشطون (آخر شراء قبل {ر:.0f} يوماً تقريباً) وأرقامهم متوسطة: {ت:.0f} عملية شراء '
                              f'وإنفاق {م:,.0f} دولار. هم الفئة التي يمكن ترقيتها إلى مميزين.')
        توصيات_المجموعات[اسم] = 'عروض "اشترِ أكثر ووفّر" وتوصية منتجات مكملة لما اشتروه لزيادة عدد مرات الشراء.'

# ترتيب الصفوف: المميزون ثم العاديون ثم الخطر
ترتيب_العرض = ['عملاء مميزون', 'عملاء عاديون', 'عملاء بخطر فقدان']

# جدول تفسير المجموعات (المطلوب التسليم الثاني)
اسم_إلى_رقم = {اسم: رقم for رقم, اسم in أسماء_المجموعات.items()}
جدول_التفسير = pd.DataFrame({
    'اسم المجموعة': ترتيب_العرض,
    'متوسط R (أيام)': [round(متوسطات_المجموعات.loc[اسم_إلى_رقم[ا], 'recency'], 1) for ا in ترتيب_العرض],
    'متوسط F (مرات)': [round(متوسطات_المجموعات.loc[اسم_إلى_رقم[ا], 'frequency'], 1) for ا in ترتيب_العرض],
    'متوسط M (دولار)': [round(متوسطات_المجموعات.loc[اسم_إلى_رقم[ا], 'monetary'], 1) for ا in ترتيب_العرض],
    'الوصف': [وصف_المجموعات[ا] for ا in ترتيب_العرض],
    'الإجراء التسويقي': [توصيات_المجموعات[ا] for ا in ترتيب_العرض],
})

عنوان('الجزء 3: جدول تفسير المجموعات (الأسماء والأوصاف والتوصيات)')
for _, صف in جدول_التفسير.iterrows():
    print(f"المجموعة: {صف['اسم المجموعة']}")
    print(f"  المتوسطات: R = {صف['متوسط R (أيام)']} يوم ، F = {صف['متوسط F (مرات)']} مرة ، M = {صف['متوسط M (دولار)']} دولار")
    print(f"  الوصف: {صف['الوصف']}")
    print(f"  الإجراء التسويقي: {صف['الإجراء التسويقي']}")
    print()


# =====================================================================
# الجزء 4: المشروع التكاملي - تقرير التجزئة النهائي
# =====================================================================
عنوان('الجزء 4 - 1: Scatter Plot للمجموعات')
ألوان = {'عملاء مميزون': 'green', 'عملاء عاديون': 'royalblue', 'عملاء بخطر فقدان': 'red'}
plt.figure(figsize=(9, 6))
for اسم in ترتيب_العرض:
    جزء = rfm[rfm['اسم_المجموعة'] == اسم]
    plt.scatter(جزء['frequency'], جزء['monetary'], c=ألوان[اسم], label=عربي(اسم), alpha=0.7, edgecolors='black')
plt.title(عربي('تجزئة العملاء: عدد الشراء مقابل إجمالي الإنفاق'))
plt.xlabel(عربي('عدد عمليات الشراء (Frequency)'))
plt.ylabel(عربي('إجمالي الإنفاق بالدولار (Monetary)'))
plt.legend()
احفظ_واعرض('رسمة_2_scatter_المجموعات.png')

عنوان('الجزء 4 - 2: جدول عدد العملاء ونسبتهم')
إجمالي_العملاء = len(rfm)
إجمالي_الإيراد = rfm['monetary'].sum()

جدول_الملخص = rfm.groupby('اسم_المجموعة').agg(
    عدد_العملاء=('monetary', 'count'),
    إجمالي_الإيراد=('monetary', 'sum'),
)
جدول_الملخص['نسبة_العملاء_%'] = (جدول_الملخص['عدد_العملاء'] / إجمالي_العملاء * 100).round(1)
جدول_الملخص['نسبة_الإيراد_%'] = (جدول_الملخص['إجمالي_الإيراد'] / إجمالي_الإيراد * 100).round(1)
جدول_الملخص['إجمالي_الإيراد'] = جدول_الملخص['إجمالي_الإيراد'].round(0)
جدول_الملخص = جدول_الملخص.loc[ترتيب_العرض]
print(جدول_الملخص)

عنوان('الجزء 4 - 3: أي مجموعة تمثل أكبر نسبة من الإيراد؟')
أكبر_مجموعة_إيراد = جدول_الملخص['نسبة_الإيراد_%'].idxmax()
أكبر_مجموعة_عدد = جدول_الملخص['نسبة_العملاء_%'].idxmax()
print(f'أكبر مجموعة من حيث الإيراد: {أكبر_مجموعة_إيراد} بنسبة {جدول_الملخص.loc[أكبر_مجموعة_إيراد, "نسبة_الإيراد_%"]}% من الإيراد')
print(f'أكبر مجموعة من حيث العدد: {أكبر_مجموعة_عدد} بنسبة {جدول_الملخص.loc[أكبر_مجموعة_عدد, "نسبة_العملاء_%"]}% من العملاء')

# رسمة إضافية: مقارنة نسبة العملاء بنسبة الإيراد
plt.figure(figsize=(8, 5))
مواقع = range(len(ترتيب_العرض))
plt.bar([م - 0.2 for م in مواقع], جدول_الملخص['نسبة_العملاء_%'], width=0.4, label=عربي('نسبة العملاء %'))
plt.bar([م + 0.2 for م in مواقع], جدول_الملخص['نسبة_الإيراد_%'], width=0.4, label=عربي('نسبة الإيراد %'))
plt.xticks(list(مواقع), [عربي(ا) for ا in ترتيب_العرض])
plt.title(عربي('نسبة العملاء مقابل نسبة الإيراد لكل مجموعة'))
plt.ylabel(عربي('النسبة %'))
plt.legend()
احفظ_واعرض('رسمة_3_العملاء_مقابل_الإيراد.png')

عنوان('الجزء 4 - 4: الملخص التنفيذي')
م = جدول_الملخص
ط = متوسطات_المجموعات
مميزون, عاديون, خطر = 'عملاء مميزون', 'عملاء عاديون', 'عملاء بخطر فقدان'

